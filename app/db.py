def _resolve_bank_dir() -> tuple[Path, str]:
    """解析只读题库目录，支持三种用法：

    * 不设 ``STUDY_BANK_DIR``：默认题库根目录，存在 ``releases/CURRENT`` 时跟随版本指针；
    * 指向题库根目录：目录里有 ``题库.db`` 时按基线库使用（便于基线回归），
      设置 ``STUDY_BANK_FOLLOW_POINTER=1`` 时改为跟随 ``releases/CURRENT``（容器挂载根目录）；
    * 指向具体发布包：直接使用（显示 ``bank_source=env``）。

    返回 ``(目录, 来源标记)``，来源标记写入就绪信息，便于核对实际读的是哪一版、是否挂错目录。
    """
    configured = os.environ.get("STUDY_BANK_DIR", "").strip()
    root = Path(configured).resolve() if configured else (ROOT.parent / "高考题库_按学科").resolve()
    pointer = root / "releases" / "CURRENT"
    follow_env = os.environ.get("STUDY_BANK_FOLLOW_POINTER", "").strip().lower()
    follow = True if not configured else not (root / "题库.db").is_file()
    if follow_env in ("0", "false", "no"):
        follow = False
    elif follow_env in ("1", "true", "yes"):
        follow = True
    if follow and pointer.is_file():
        try:
            # 兼容 PowerShell 写出的 UTF-8 BOM 与行尾空白。
            version = pointer.read_text(encoding="utf-8-sig").strip()
        except OSError:
            version = ""
        candidate = root / "releases" / version
        if version and (candidate / "题库.db").is_file():
            return candidate, "pointer:" + version
    return root, ("env" if configured else "default")


