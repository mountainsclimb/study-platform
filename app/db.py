# 进程级 PostgreSQL 连接池（P1）：None=尚未初始化，False=已确认缺包走回退。
_pg_pool = None
_pg_pool_lock = threading.Lock()
_pg_pool_warned = False
_AppCursor = None


def _app_cursor():
    """psycopg 游标子类：允许挂 ``lastrowid``，与现有 SQLite 风格调用方兼容。"""
    global _AppCursor
    if _AppCursor is None:
        try:
            import psycopg
        except ImportError as exc:
            raise RuntimeError("DATABASE_URL 需要 psycopg[binary] 驱动") from exc

        class AppCursor(psycopg.Cursor):
            # The low-level C cursor does not allow setting arbitrary attributes.
            lastrowid = None

        _AppCursor = AppCursor
    return _AppCursor


def _postgres_connect_kwargs() -> dict:
    return {
        "connect_timeout": 10,
        "row_factory": _row_factory,
        "cursor_factory": _app_cursor(),
    }


def _open_postgres():
    try:
        import psycopg
    except ImportError as exc:
        raise RuntimeError("DATABASE_URL 需要 psycopg[binary] 驱动") from exc
    return psycopg.connect(os.environ["DATABASE_URL"].strip(), **_postgres_connect_kwargs())


def _pool_kwargs() -> dict:
    """ConnectionPool 的连接参数（单独抽出便于离线测试用伪驱动替换）。"""
    return _postgres_connect_kwargs()


def _warn_pool_fallback() -> None:
    global _pg_pool_warned
    if _pg_pool_warned:
        return
    _pg_pool_warned = True
    _log.warning(
        "缺少可选依赖 psycopg_pool：PostgreSQL 回退为每次新建连接（并发成本升高）。"
        "请按 deploy/requirements.txt 安装 psycopg_pool>=3.2,<4 后重启以启用连接池。"
    )


def _get_pool():
    """懒创建进程级连接池；缺 ``psycopg_pool`` 时返回 None 并回退旧行为。"""
    global _pg_pool
    if _pg_pool is not None:
        return _pg_pool or None
    with _pg_pool_lock:
        if _pg_pool is not None:
            return _pg_pool or None
        try:
            from psycopg_pool import ConnectionPool
        except ImportError:
            _warn_pool_fallback()
            _pg_pool = False
            return None
        pool = ConnectionPool(
            os.environ["DATABASE_URL"].strip(),
            min_size=2, max_size=20, open=True,
            kwargs=_pool_kwargs(), name="zhixu-app",
        )
        _pg_pool = pool
        atexit.register(close_pool)
        return pool


def close_pool() -> None:
    """关闭进程级 PostgreSQL 连接池（atexit 自动调用；lifespan 可显式接入）。"""
    global _pg_pool
    with _pg_pool_lock:
        pool, _pg_pool = _pg_pool, None
    if pool is not None and pool is not False:
        try:
            pool.close()
        except Exception:  # 关闭阶段不能因池异常阻断进程退出
            _log.warning("PostgreSQL 连接池关闭失败", exc_info=True)


@contextmanager
def connection(*, attach_bank: bool = False):
    if postgres_enabled():
        pool = _get_pool()
        if pool is None:
            # 回退路径：无 psycopg_pool 时保持旧行为（每次新建连接），不改变语义。
            raw = _open_postgres()
            con = _Postgres(raw)
            try:
                if attach_bank:
                    _ensure_postgres_bank(con)
                    con.commit()
                yield con
                con.commit()
            except BaseException:
                try:
                    raw.rollback()
                except Exception:
                    pass
                raise
            finally:
                raw.close()
            return
        with pool.connection() as raw:
            con = _Postgres(raw)
            try:
                if attach_bank:
                    _ensure_postgres_bank(con)
                    con.commit()
                yield con
            except BaseException:
                try:
                    raw.rollback()
                except Exception:
                    pass
                raise
            else:
                raw.commit()
        return

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    db_file = (DATA_DIR / "app.sqlite3").resolve()
    if attach_bank:
        con = sqlite3.connect(db_file.as_uri(), uri=True, timeout=20)
    else:
        con = sqlite3.connect(db_file, timeout=20)
    con.row_factory = sqlite3.Row
    try:
        con.execute("PRAGMA foreign_keys=ON")
        con.execute("PRAGMA busy_timeout=20000")
        if attach_bank:
            bank_path = bank_db_path()
            if not bank_path.is_file():
                raise FileNotFoundError("未找到题库，请检查 STUDY_BANK_DIR 配置")
            con.execute("ATTACH DATABASE ? AS bank", (bank_path.resolve().as_uri() + "?mode=ro",))
        yield con
        con.commit()
    except Exception:
        con.rollback()
        raise
    finally:
        con.close()


def get_setting(key: str, default: str | None = None) -> str | None:
    """Read an operator setting; the table may not exist before migrations run."""
    try:
        with connection() as con:
            row = con.execute("SELECT value FROM app_settings WHERE key=?", (key,)).fetchone()
    except Exception:
        return default
    return row[0] if row else default


def set_setting(key: str, value: str) -> None:
    with connection() as con:
        write_lock(con, "app-settings")
        con.execute(
            "INSERT INTO app_settings(key,value,updated_at) VALUES (?,?,?) "
            "ON CONFLICT(key) DO UPDATE SET value=excluded.value, updated_at=excluded.updated_at",
            (key, value, utcnow()),
        )


def write_lock(con, scope):
    """Serialize transactions in a named write path across application processes."""
    if isinstance(con, _Postgres):
        return con.execute(
            "SELECT pg_advisory_xact_lock(hashtextextended(current_schema() || ':' || ?, 0))",
            (f"zhixu:{scope}",),
        )
    return con.execute("BEGIN IMMEDIATE")


def table_names(con):
    sql = (
        "SELECT table_name FROM information_schema.tables WHERE table_schema=current_schema()"
        if isinstance(con, _Postgres)
        else "SELECT name FROM sqlite_master WHERE type='table'"
    )
    return {row[0] for row in con.execute(sql)}


def username_predicate(con):
    if isinstance(con, _Postgres):
        return """LOWER(username COLLATE "C")=LOWER(CAST(? AS TEXT) COLLATE "C")"""
    return "username=?"


def ensure_column(con, table: str, column: str, definition: str):
    if isinstance(con, _Postgres):
        con.execute(f'ALTER TABLE "{table}" ADD COLUMN IF NOT EXISTS "{column}" {definition}')
    else:
        existing = {row[1] for row in con.execute(f'PRAGMA table_info("{table}")')}
        if column not in existing:
            con.execute(f'ALTER TABLE "{table}" ADD COLUMN "{column}" {definition}')


@lru_cache(maxsize=8)
def _bank_digest(signature):
    digest = hashlib.sha256()
    for path_to_hash, _, _ in signature:
        with Path(path_to_hash).open("rb") as source:
            while chunk := source.read(1 << 20):
                digest.update(chunk)
    return digest.hexdigest()


def _bank_signature(path):
    files = (path, path.with_name(path.name + "-wal"))
    result = []
    for file in files:
        try:
            stat = file.stat()
        except FileNotFoundError:
            if file == path:
                raise
            continue
        if stat.st_size:
            result.append((str(file), stat.st_mtime_ns, stat.st_size))
    return tuple(result)


PG_BANK_INDEX_KEY = "pg_bank_search_v3_sha256"
# 进程内已验证的题库摘要：题库未变化时 O(1) 返回，不再每个 attach_bank 连接都查 meta。
_pg_bank_verified_digest: str | None = None


def _sqlite_group_materials(source) -> dict[str, str]:
    """groups.group_id → material_text，供 PG 镜像在 COPY 时直接落材料镜像列。"""
    columns = {row[1] for row in source.execute("PRAGMA table_info(groups)")}
    if not {"group_id", "material_text"} <= columns:
        return {}
    return {
        str(group_id): material or ""
        for group_id, material in source.execute("SELECT group_id, material_text FROM groups")
        if group_id
    }


def _ensure_postgres_bank(con):
    """Transactionally refresh the PostgreSQL mirror used in cross-table reads.

    P0（PG 锁风暴 / GIN 索引失效）修复要点：

    * 派生列 ``stem_compact`` / ``search_material_text`` 在 Python 侧算好随 COPY 直接写入，
      不再 COPY 后逐行 ``ALTER TABLE`` + ``UPDATE``（7,659 次双倍死元组 + ACCESS EXCLUSIVE）；
    * 索引统一在数据装载之后创建，``ANALYZE`` 放在最后，统计信息不会落后于数据；
    * 关键词检索命中 ``stem_compact`` 的 GIN(trgm) 索引（不再被 COALESCE 绕开）；
    * 题库摘要不变时只做进程内 O(1) 判定（必要时一次 ``bank_meta`` 查询），不重复 DDL。
    """
    from psycopg import sql

    global _pg_bank_verified_digest
    path = bank_db_path().resolve()
    if not path.is_file():
        raise FileNotFoundError("未找到题库，请检查 STUDY_BANK_DIR 配置")
    digest = _bank_digest(_bank_signature(path))
    if _pg_bank_verified_digest == digest:
        return
    index_key = PG_BANK_INDEX_KEY
    lookup = (
        "SELECT value FROM bank_meta WHERE key=? "
        "AND to_regclass('bank.questions') IS NOT NULL AND to_regclass('bank.groups') IS NOT NULL"
    )
    meta = con.execute(lookup, (index_key,)).fetchone()
    if meta and meta[0] == digest:
        # 题库未变化，但泄密标记是独立应用表：旧库可能还没有，同样按摘要补齐。
        from .practice import _install_bank_leak_flags
        _pg_bank_verified_digest = digest
        _install_bank_leak_flags(con, digest)
        return
    write_lock(con, "bank-mirror")
    meta = con.execute(lookup, (index_key,)).fetchone()
    if meta and meta[0] == digest:
        from .practice import _install_bank_leak_flags
        _pg_bank_verified_digest = digest
        _install_bank_leak_flags(con, digest)
        return

    # 检索用紧凑文本（去空白与标点）在 Python 侧计算，避免各数据库正则方言差异；
    # 与 SQLite FTS 的 stem_compact 使用同一函数，双引擎检索口径一致。
    from .practice import _compact_search_text, _group_key

    with closing(sqlite3.connect(path.as_uri() + "?mode=ro", uri=True, timeout=20)) as source:
        source.execute("BEGIN")
        con.execute("CREATE SCHEMA IF NOT EXISTS bank")
        con.execute("DROP TABLE IF EXISTS bank.questions, bank.groups")
        group_materials = _sqlite_group_materials(source)
        question_columns: set[str] = set()
        group_columns: set[str] = set()
        for table in ("questions", "groups"):
            columns = source.execute(f"PRAGMA table_info({table})").fetchall()
            if not columns or any(col[2] not in {"TEXT", "INTEGER"} for col in columns):
                raise ValueError(f"题库表 {table} 的结构无法同步")
            names = [col[1] for col in columns]
            if table == "questions":
                question_columns = set(names)
                derived = ["stem_compact", "search_material_text"]
            else:
                group_columns = set(names)
                derived = []
            relation = sql.Identifier("bank", table)
            definitions = [
                sql.SQL("{} {}{}").format(
                    sql.Identifier(name), sql.SQL(kind),
                    sql.SQL(" PRIMARY KEY" if primary_key else " NOT NULL" if required else ""),
                )
                for _, name, kind, required, _, primary_key in columns
            ]
            definitions.extend(
                sql.SQL("{} TEXT").format(sql.Identifier(name)) for name in derived
            )
            con.raw.execute(sql.SQL("CREATE TABLE {} ({})").format(relation, sql.SQL(", ").join(definitions)))
            copy_columns = [*names, *derived]
            copy_statement = sql.SQL("COPY {} ({}) FROM STDIN").format(
                relation, sql.SQL(", ").join(sql.Identifier(name) for name in copy_columns)
            )
            if table != "questions":
                with con.raw.cursor().copy(copy_statement) as copy:
                    for row in source.execute(f"SELECT * FROM {table}"):
                        copy.write_row(row)
                continue
            stem_index = names.index("stem_plain") if "stem_plain" in names else None
            doc_index = names.index("doc_id") if "doc_id" in names else None
            group_index = names.index("group_id") if "group_id" in names else None
            with con.raw.cursor().copy(copy_statement) as copy:
                for row in source.execute("SELECT * FROM questions"):
                    stem = (row[stem_index] if stem_index is not None else "") or ""
                    group_id = row[group_index] if group_index is not None else None
                    key = _group_key({
                        "group_id": group_id,
                        "doc_id": row[doc_index] if doc_index is not None else None,
                    })
                    copy.write_row((
                        *row,
                        _compact_search_text(stem),
                        group_materials.get(key) or "",
                    ))

    # 快照契约 §5 新增列索引；旧题库没有这些列时保持原样。
    snapshot_indexes = ""
    if "practice_status" in question_columns:
        snapshot_indexes += "CREATE INDEX idx_q_practice_status ON bank.questions(practice_status);\n"
    if "parent_source_question_id" in question_columns:
        snapshot_indexes += "CREATE INDEX idx_q_parent_src ON bank.questions(parent_source_question_id);\n"
    if "doc_id" in group_columns:
        snapshot_indexes += "CREATE INDEX idx_g_doc ON bank.groups(doc_id);\n"
    # 顺序固定：COPY 装载 → 建索引 → ANALYZE（旧实现 ANALYZE 在 UPDATE 之前，统计陈旧）。
    con.executescript("""
        CREATE INDEX questions_filters ON bank.questions(subject, year, type, province);
        CREATE INDEX questions_stem_compact_trgm ON bank.questions USING GIN(stem_compact gin_trgm_ops);
        CREATE INDEX questions_paper_trgm ON bank.questions USING GIN(paper_name gin_trgm_ops);
        CREATE INDEX questions_material_trgm ON bank.questions USING GIN(search_material_text gin_trgm_ops);
    """ + snapshot_indexes + """
        ANALYZE bank.questions;
        ANALYZE bank.groups;
    """)
    con.execute(
        "INSERT INTO bank_meta(key,value) VALUES (?,?) "
        "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
        (index_key, digest),
    )
    _pg_bank_verified_digest = digest
    # 与 FTS 同一条「题库摘要」刷新路径：批量重算检索期泄密标记。
    # PG 模式只写应用库 bank_leak_flags，不再冗余维护从不查询的 bank_search_meta。
    from .practice import _install_bank_leak_flags
    _install_bank_leak_flags(con, digest)


def _apply_migrations(con):
    if not isinstance(con, _Postgres):
        write_lock(con, "base-schema")
    con.execute("""
        CREATE TABLE IF NOT EXISTS schema_version (
            version TEXT PRIMARY KEY,
            applied_at TEXT NOT NULL
        )
    """)
    applied = {r[0] for r in con.execute("SELECT version FROM schema_version")}
    for sql_file in sorted(MIGRATIONS_DIR.glob("*.sql")):
        ver = sql_file.name
        if ver in applied:
            continue
        script = sql_file.read_text(encoding="utf-8-sig")
        if isinstance(con, _Postgres):
            con.executescript(script)
        else:
            # sqlite3.executescript would commit the transaction protecting the
            # migration markers. Use SQLite's parser to find statement boundaries.
            statement = ""
            for character in script:
                statement += character
                if character == ";" and sqlite3.complete_statement(statement):
                    con.execute(statement)
                    statement = ""
            if statement.strip():
                con.execute(statement)
        con.execute("INSERT INTO schema_version(version, applied_at) VALUES (?,?)", (ver, utcnow()))


def init_db():
    with connection() as con:
        if isinstance(con, _Postgres):
            write_lock(con, "base-schema")
            legacy = con.execute(
                "SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() "
                "AND table_name='ai_documents' AND column_name='chunks_json' AND data_type='jsonb'"
            ).fetchone()
            if legacy:
                raise RuntimeError("PostgreSQL 数据库使用旧部署样例结构，请指定新数据库后启动")
            con.execute("CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public")
        else:
            con.execute("PRAGMA journal_mode=WAL")
        con.executescript("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY,
                username TEXT NOT NULL UNIQUE COLLATE NOCASE,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'student' CHECK(role IN ('admin','student')),
                created_at TEXT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS sessions (
                token_hash TEXT PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                expires_at TEXT NOT NULL,
                created_at TEXT NOT NULL
            );
            CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
        """)
        if isinstance(con, _Postgres):
            con.execute("""CREATE UNIQUE INDEX IF NOT EXISTS users_username_nocase ON users (LOWER(username COLLATE "C"))""")
        _apply_migrations(con)
