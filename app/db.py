# SQLite declares these single-column IDs as rowid aliases; PostgreSQL uses identities.
# Keep cursor.lastrowid available to existing callers by reading the inserted ID itself.
_ID_TABLES = frozenset({
    "users", "knowledge_points", "methods", "ai_models", "ai_usage", "ai_explanations",
    "note_versions", "prompt_templates", "recovery_codes", "eval_runs", "attempts",
    "ai_providers", "ai_uploads", "ai_documents", "ai_notes", "ai_jobs", "ai_audit",
    "content_issues",
})
_INSERT_TABLE = re.compile(r"^\s*INSERT\s+INTO\s+([a-z_][a-z_0-9]*)\b", re.IGNORECASE)
_QMARK = re.compile(r"""'(?:[^']|'')*'|"(?:[^"]|"")*"|--[^\n]*|/\*[\s\S]*?\*/|\?""")


class _Row(tuple):
    """A PostgreSQL result with sqlite3.Row's index and mapping access."""

    def __new__(cls, values, columns):
        row = super().__new__(cls, values)
        row._columns = columns
        return row

    def keys(self):
        return self._columns

    def __getitem__(self, key):
        if isinstance(key, str):
            try:
                key = self._columns.index(key)
            except ValueError:
                raise IndexError("No item with that key") from None
        return super().__getitem__(key)


def _row_factory(cursor):
    columns = tuple(col.name for col in cursor.description or ())
    return lambda values: _Row(values, columns)


def _postgres_params(statement):
    # Psycopg uses %s; leave '?' inside string literals, quoted names and comments alone.
    return _QMARK.sub(lambda match: "%s" if match[0] == "?" else match[0], statement.replace("%", "%%"))


class _Postgres:
    def __init__(self, raw):
        self.raw = raw

    def execute(self, statement, params=None):
        insert = _INSERT_TABLE.match(statement)
        returns_id = (
            insert is not None
            and insert[1].lower() in _ID_TABLES
            and not re.search(r"\bRETURNING\b", statement, re.IGNORECASE)
        )
        if returns_id:
            statement = statement.rstrip().removesuffix(";") + " RETURNING id"
        cursor = self.raw.execute(_postgres_params(statement) if params else statement, params or None)
        cursor.lastrowid = None
        if returns_id:
            row = cursor.fetchone()
            cursor.lastrowid = row[0] if row else None
        return cursor

    def executescript(self, script):
        # Only application-owned schema SQL is passed here. Keep all DDL transactional.
        script = re.sub(
            r"\bid INTEGER PRIMARY KEY\b",
            "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            script,
            flags=re.IGNORECASE,
        )
        script = re.sub(r"\s+COLLATE NOCASE\b", "", script, flags=re.IGNORECASE)
        return self.raw.execute(script)

    def commit(self):
        self.raw.commit()


def utcnow():
    return datetime.now(timezone.utc).isoformat()


def bank_db_path() -> Path:
    return BANK_DIR / "题库.db"


@lru_cache(maxsize=8)
def _bank_version_of(path: str, mtime_ns: int, size: int) -> str:
    probe = sqlite3.connect(Path(path).as_uri() + "?mode=ro", uri=True, timeout=10)
    try:
        row = probe.execute("SELECT bank_version FROM questions LIMIT 1").fetchone()
        return str(row[0]) if row and row[0] else ""
    except sqlite3.Error:
        return ""
    finally:
        probe.close()


def bank_version_hint() -> str:
    """题库版本（快照包才带）；旧库返回空字符串。"""
    path = bank_db_path()
    try:
        stat = path.stat()
    except OSError:
        return ""
    try:
        return _bank_version_of(str(path.resolve()), stat.st_mtime_ns, stat.st_size)
    except sqlite3.Error:
        return ""


