def json_load(raw, default=None):
    """宽松解析数据库 TEXT JSON（双引擎行为一致）。"""
    if raw is None or raw == "":
        return default
    if isinstance(raw, (dict, list)):
        return raw
    try:
        value = json.loads(raw)
    except (TypeError, ValueError):
        return default
    if value is None:
        return default
    if default is not None and not isinstance(value, type(default)):
        return default
    return value


def json_dump(value) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True)


def now() -> datetime:
    return datetime.now(timezone.utc)


def iso_in_days(days: int) -> str:
    return (now() + timedelta(days=int(days))).isoformat()


def normalize_timestamp(value) -> str | None:
    """把外部传入的到期时间规整成 UTC ISO-8601（未带时区按 UTC 处理）。

    统一成 ``+00:00`` 偏移后，``expires_at > utcnow()`` 才有可比较的字符串语义。
    """
    text = str(value or "").strip()
    if not text:
        return None
    try:
        parsed = datetime.fromisoformat(text.replace("Z", "+00:00"))
    except ValueError:
        raise ValueError("到期时间格式不正确，请使用 ISO-8601，例如 2027-01-01T00:00:00Z")
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc).isoformat()


