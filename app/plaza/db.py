def _row_dict(row):
    if row is None:
        return None
    if isinstance(row, dict):
        return dict(row)
    try:
        return dict(row)
    except Exception:  # noqa: BLE001 - 行对象不可解析按不存在处理
        return None


def load_submission(con, submission_id: int) -> dict | None:
    row = con.execute("SELECT * FROM plaza_submissions WHERE id=?", (int(submission_id),)).fetchone()
    return _row_dict(row)


