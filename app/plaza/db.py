def identity_effective_status(row) -> str:
    """身份申请的有效状态：已通过但过了到期时间按 ``expired`` 处理（行保留供审计）。"""
    item = row if isinstance(row, dict) else {}
    status = str(item.get("status") or "")
    expires = str(item.get("expires_at") or "")
    if status == "approved" and expires and expires <= utcnow():
        return "expired"
    return status


