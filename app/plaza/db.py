_initialized: set[str] = set()
_init_lock = threading.Lock()


def _db_identity() -> str:
    """当前应用库身份：测试每个用例切换 ``DATA_DIR``，必须按库分别建表。"""
    if app_db.postgres_enabled():
        return "postgres:" + os.environ.get("DATABASE_URL", "").strip()
    return "sqlite:" + str((app_db.DATA_DIR / "app.sqlite3").resolve())


def ensure_tables() -> None:
    """幂等建表；同一应用库在本进程内只执行一次 DDL。"""
    key = _db_identity()
    if key in _initialized:
        return
    with _init_lock:
        if key in _initialized:
            return
        with connection() as con:
            con.executescript(_SCHEMA)
        _initialized.add(key)


