# 写事务基础：显式主键 + 事件
# ---------------------------------------------------------------------------

def next_id(con, table: str) -> int:
    """在已持有 ``write_lock(con, "plaza-write")`` 的事务内分配主键。"""
    row = con.execute(f"SELECT COALESCE(MAX(id), 0) + 1 FROM {table}").fetchone()
    return int(row[0] or 1)


def insert_row(con, table: str, values: dict) -> int:
    """插入一行并返回显式主键（``values`` 含 ``id`` 时以其为准）。"""
    row_id = int(values.get("id") or next_id(con, table))
    data = {**values, "id": row_id}
    columns = list(data)
    placeholders = ", ".join("?" for _ in columns)
    con.execute(
        f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({placeholders})",
        tuple(data[column] for column in columns),
    )
    return row_id


def record_event(con, submission_id, actor_id, action: str, from_status: str = "",
                 to_status: str = "", reason: str = "", payload=None) -> int:
    """写一条广场事件（与状态更新同事务；事件链是审核追溯的唯一入口）。"""
    return insert_row(con, "plaza_events", {
        "submission_id": int(submission_id) if submission_id is not None else None,
        "actor_id": int(actor_id) if actor_id is not None else None,
        "action": str(action),
        "from_status": str(from_status or ""),
        "to_status": str(to_status or ""),
        "reason": str(reason or "")[:2000],
        "payload_json": json_dump(payload or {}),
        "created_at": utcnow(),
    })


